const assert = require('node:assert/strict');
const {distance,fenceStatus} = require('./static/geo.js');
const fence={south:38,north:39,west:-77,east:-76,warning_m:1000};
const now=Date.now();
const packet=(lat,lon)=>({has_position:true,latitude_deg:lat,longitude_deg:lon,received_at:new Date(now).toISOString()});
assert.ok(Math.abs(distance([0,0],[0,.001])-111.19508)<.001);
assert.equal(fenceStatus(fence,packet(38.5,-76.5),true,now).kind,'inside');
assert.equal(fenceStatus(fence,packet(38.0001,-76.5),true,now).kind,'near');
assert.equal(fenceStatus(fence,packet(37.99,-76.5),true,now).kind,'outside');
assert.equal(fenceStatus(fence,packet(38,-76.5),true,now).meters,0);
assert.equal(fenceStatus(fence,{...packet(38.5,-76.5),has_position:false},true,now).kind,'unknown');
assert.equal(fenceStatus(fence,{...packet(38.5,-76.5),received_at:'bad'},true,now).kind,'unknown');
assert.equal(fenceStatus(fence,packet(38.5,-76.5),true,now+16000).kind,'unknown');
assert.equal(fenceStatus(fence,packet(38.5,-76.5),false,now+16000).kind,'inside');
assert.equal(fenceStatus(fence,null,true,now).kind,'unknown');
assert.equal(fenceStatus(null,packet(38.5,-76.5),true,now).kind,'none');
const outside=fenceStatus(fence,packet(37.99,-77.01),false,now);
assert.equal(outside.kind,'outside');assert.ok(outside.meters>1000);
assert.equal(fenceStatus(fence,{...packet(38.5,-76.5),duplicate:true},true,now).kind,'unknown');
console.log('Geometry checks passed: distance, inside/near/outside, edge, stale GPS, missing fix, replay, and duplicates.');
